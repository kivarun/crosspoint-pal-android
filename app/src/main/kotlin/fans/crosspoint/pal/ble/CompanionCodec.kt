package fans.crosspoint.pal.ble

/**
 * Strict bounded codec for the companion protocol v1.
 *
 * Encoding mirrors the firmware contract: complete UTF-8 JSON objects of at
 * most [CompanionProtocol.MAX_MESSAGE_BYTES], with title/body truncated at
 * UTF-8 code-point boundaries so both sides agree on what was stored.
 * Escaping is accounted for because the reader silently drops control values
 * above the byte cap. Decoding is fail closed: anything that is not a
 * bounded, well-formed v1 message decodes to [DeviceMessage.Unknown] or
 * throws [MalformedNotification].
 */
object CompanionCodec {

    /**
     * Fixed structural bytes of a `content` message: everything except the
     * three string values (title and body enter as their escaped, quoted
     * JSON form; contentId as its safe plain form).
     */
    const val CONTENT_OVERHEAD_BYTES = 48

    fun hello(): ByteArray = """{"op":"hello","version":${CompanionProtocol.VERSION}}""".toByteArray(Charsets.UTF_8)

    /**
     * Encodes a content message. Title and body are truncated at code-point
     * boundaries so the encoded message respects the per-field byte caps and
     * the overall [CompanionProtocol.MAX_MESSAGE_BYTES] cap, escape forms
     * included. The contentId is pre-generated by the caller and never
     * truncated: it must already satisfy the charset and length contract.
     */
    fun content(title: String, body: String, contentId: String): ByteArray {
        require(isPlainId(contentId)) { "contentId violates the protocol charset or length" }

        val titleRaw = truncateToBytes(title, CompanionProtocol.MAX_TITLE_BYTES)
        val titleEncoded = encodeJsonString(titleRaw)
        val titleEncodedBytes = titleEncoded.toByteArray(Charsets.UTF_8).size
        val idEncodedBytes = contentId.toByteArray(Charsets.UTF_8).size

        // All budgets are UTF-8 byte budgets: the reader counts bytes, not
        // characters, and escaping can inflate the raw form, so the body
        // truncation shrinks until the encoded body fits the message cap.
        val messageBudget = CompanionProtocol.MAX_MESSAGE_BYTES - CONTENT_OVERHEAD_BYTES -
            titleEncodedBytes - idEncodedBytes
        var bodyRaw = truncateToBytes(body, minOf(CompanionProtocol.MAX_BODY_BYTES, messageBudget))
        var encodedBody = encodeJsonString(bodyRaw)
        while (encodedBody.toByteArray(Charsets.UTF_8).size > messageBudget && bodyRaw.isNotEmpty()) {
            val overshoot = encodedBody.toByteArray(Charsets.UTF_8).size - messageBudget
            val rawLength = bodyRaw.toByteArray(Charsets.UTF_8).size
            bodyRaw = truncateToBytes(body, rawLength - maxOf(1, overshoot / 6))
            encodedBody = encodeJsonString(bodyRaw)
        }

        val json = """{"op":"content","title":$titleEncoded,"body":$encodedBody,"contentId":"$contentId"}"""
        val encoded = json.toByteArray(Charsets.UTF_8)
        require(encoded.size <= CompanionProtocol.MAX_MESSAGE_BYTES) {
            "encoded content message exceeds the protocol bound"
        }
        return encoded
    }

    /**
     * Decodes one reader notification. Returns [DeviceMessage.Unknown] for
     * well-formed JSON that is not a v1 message; throws
     * [MalformedNotification] for input that is not JSON at all or exceeds
     * the notification bound.
     */
    fun decodeNotification(data: ByteArray): DeviceMessage {
        if (data.isEmpty() || data.size > CompanionProtocol.MAX_NOTIFICATION_BYTES) {
            throw MalformedNotification()
        }
        val json = JsonParser(data).parseObject() ?: throw MalformedNotification()
        // A known op with a broken shape fails closed; an unknown op stays
        // Unknown so the session decides.
        val op = json.string("op") ?: throw MalformedNotification()
        return when (op) {
            "hello_ack" -> DeviceMessage.HelloAck(version = json.integer("version") ?: throw MalformedNotification())
            "content_ack" -> {
                val id = json.string("contentId") ?: throw MalformedNotification()
                if (!isPlainId(id)) throw MalformedNotification()
                DeviceMessage.ContentAck(id)
            }
            "button" -> {
                val button = json.string("button") ?: throw MalformedNotification()
                val pressed = json.boolean("pressed") ?: throw MalformedNotification()
                if (button in BUTTON_NAMES) DeviceMessage.Button(button, pressed) else DeviceMessage.Unknown
            }
            "error" -> {
                val code = json.string("code") ?: throw MalformedNotification()
                val message = json.string("message") ?: throw MalformedNotification()
                if (code.isEmpty() || code.any { it.code < 0x20 || it == '"' || it == '\\' }) {
                    throw MalformedNotification()
                }
                DeviceMessage.Error(code, message)
            }
            else -> DeviceMessage.Unknown
        }
    }

    /** contentId charset shared by the encoder and the decoder. */
    fun isPlainId(id: String): Boolean =
        id.isNotEmpty() &&
            id.length <= CompanionProtocol.MAX_CONTENT_ID_BYTES &&
            id.all { it in CompanionProtocol.CONTENT_ID_CHARS }

    /**
     * Truncates a string to at most [maxBytes] UTF-8 bytes at a code-point
     * boundary, never splitting a multi-byte sequence. The result is always
     * valid UTF-8.
     */
    fun truncateToBytes(value: String, maxBytes: Int): String {
        if (maxBytes <= 0) return ""
        val raw = value.toByteArray(Charsets.UTF_8)
        if (raw.size <= maxBytes) return value
        var bytes = 0
        var keep = 0
        for (codePoint in value.codePoints()) {
            val size = utf8Length(codePoint)
            if (bytes + size > maxBytes) break
            bytes += size
            keep += Character.charCount(codePoint)
        }
        return value.substring(0, keep)
    }

    private val BUTTON_NAMES = setOf(
        CompanionProtocol.BUTTON_BACK,
        CompanionProtocol.BUTTON_CONFIRM,
        CompanionProtocol.BUTTON_LEFT,
        CompanionProtocol.BUTTON_RIGHT,
        CompanionProtocol.BUTTON_UP,
        CompanionProtocol.BUTTON_DOWN,
    )

    private fun utf8Length(codePoint: Int): Int = when {
        codePoint < 0x80 -> 1
        codePoint < 0x800 -> 2
        codePoint < 0x10000 -> 3
        else -> 4
    }

    /**
     * JSON string literal for the wire. Control characters, quotes and
     * backslashes are escaped exactly the way the firmware reader accepts
     * them (short forms plus \uXXXX).
     */
    private fun encodeJsonString(value: String): String = buildString(value.length + 2) {
        append('"')
        for (c in value) {
            when {
                c == '"' -> append("\\\"")
                c == '\\' -> append("\\\\")
                c == '\b' -> append("\\b")
                c == '\u000C' -> append("\\f")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c.code < 0x20 -> append("\\u" + c.code.toString(16).padStart(4, '0'))
                else -> append(c)
            }
        }
        append('"')
    }
}

/** A reader notification that is not decodable JSON within the bounds. */
class MalformedNotification : Exception()
